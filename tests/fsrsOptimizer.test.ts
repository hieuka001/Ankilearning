test('evaluateWeights is deterministic and counts samples correctly', () => {
  const sequences = buildReviewSequences(generateSyntheticCards(30));
  const first = evaluateWeights(sequences, DEFAULT_FSRS_WEIGHTS);
  const second = evaluateWeights(sequences, DEFAULT_FSRS_WEIGHTS);

  assert.deepEqual(first, second);
  assert.equal(first.samples, countPredictionSamples(sequences));
  assert.ok(Number.isFinite(first.logLoss) && first.logLoss > 0);
});

test('evaluateWeights scores the true weights better than the defaults on synthetic data', () => {
  const sequences = buildReviewSequences(generateSyntheticCards());
  assert.ok(countPredictionSamples(sequences) >= MIN_OPTIMIZATION_SAMPLES);

  const defaults = evaluateWeights(sequences, DEFAULT_FSRS_WEIGHTS);
  const truth = evaluateWeights(sequences, TRUE_WEIGHTS);
  assert.ok(
    truth.logLoss < defaults.logLoss - 0.005,
    `true weights (${truth.logLoss}) should clearly beat defaults (${defaults.logLoss})`,
  );
});

