test('optimizeWeights clearly improves log-loss starting from the defaults', async () => {
  const sequences = buildReviewSequences(generateSyntheticCards());
  const result = await optimizeWeights(sequences, DEFAULT_FSRS_WEIGHTS);

  assert.equal(result.status, 'ok');
  if (result.status !== 'ok') return;
  assert.equal(result.samples, countPredictionSamples(sequences));
  assert.ok(
    result.logLossAfter < result.logLossBefore - 0.005,
    `expected a clear improvement, got ${result.logLossBefore} -> ${result.logLossAfter}`,
  );
  assert.equal(result.weights.length, DEFAULT_FSRS_WEIGHTS.length);
  result.weights.forEach((weight, index) => {
    const [low, high] = FSRS_WEIGHT_BOUNDS[index];
    assert.ok(weight >= low && weight <= high, `weight ${index} stays in bounds`);
  });
});

test('optimizeWeights reports insufficient-data below the sample threshold', async () => {
  const sequences = buildReviewSequences(generateSyntheticCards(5));
  assert.ok(countPredictionSamples(sequences) < MIN_OPTIMIZATION_SAMPLES);

  const result = await optimizeWeights(sequences, DEFAULT_FSRS_WEIGHTS);
  assert.equal(result.status, 'insufficient-data');
});

