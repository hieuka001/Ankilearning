test('buildReviewSequences drops invalid entries, sorts, and drops short sequences', () => {
  const sequences = buildReviewSequences([
    {
      id: 'a',
      reviewHistory: [
        { rating: 'good', reviewTime: '2026-01-03T00:00:00.000Z' },
        { rating: 'again', reviewTime: '2026-01-01T00:00:00.000Z' },
        { rating: 'nonsense', reviewTime: '2026-01-02T00:00:00.000Z' },
        { rating: 'easy', reviewTime: 'not-a-date' },
        null,
        'garbage',
        { rating: 'hard', reviewTime: '2026-01-02T00:00:00.000Z' },
      ],
    },
    { id: 'b', reviewHistory: [{ rating: 'good', reviewTime: '2026-01-01T00:00:00.000Z' }] },
    { id: 'c', reviewHistory: 'not-an-array' },
    { id: 'd' },
    null,
    undefined,
  ]);

  assert.equal(sequences.length, 1);
  assert.equal(sequences[0].cardId, 'a');
  assert.deepEqual(
    sequences[0].reviews.map((review) => review.rating),
    ['again', 'hard', 'good'],
  );
  assert.equal(countPredictionSamples(sequences), 2);
});

