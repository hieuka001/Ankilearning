test('normalizeSchedulerConfig keeps, drops, or clamps fsrsWeights correctly', () => {
  const absent = normalizeSchedulerConfig({});
  assert.equal(absent.fsrsWeights, undefined);
  assert.equal(absent.fsrsOptimizedAt, undefined);

  const wrongLength = normalizeSchedulerConfig({ fsrsWeights: [1, 2, 3] });
  assert.equal(wrongLength.fsrsWeights, undefined);

  const withNaN = normalizeSchedulerConfig({
    fsrsWeights: DEFAULT_FSRS_WEIGHTS.map((w, i) => (i === 4 ? Number.NaN : w)),
  });
  assert.equal(withNaN.fsrsWeights, undefined);

  const clamped = normalizeSchedulerConfig({
    fsrsWeights: DEFAULT_FSRS_WEIGHTS.map(() => 9999),
    fsrsOptimizedAt: '2026-11-04T00:00:00.000Z',
    fsrsOptimizationSamples: 1234,
  });
  assert.ok(clamped.fsrsWeights);
  clamped.fsrsWeights!.forEach((weight, index) => {
    assert.equal(weight, FSRS_WEIGHT_BOUNDS[index][1]);
  });
  assert.equal(clamped.fsrsOptimizedAt, '2026-11-04T00:00:00.000Z');
  assert.equal(clamped.fsrsOptimizationSamples, 1234);

  const exactDefaults = normalizeSchedulerConfig({ fsrsWeights: [...DEFAULT_FSRS_WEIGHTS] });
  assert.deepEqual(exactDefaults.fsrsWeights, [...DEFAULT_FSRS_WEIGHTS]);
});

test('scheduler actually schedules with personalized weights when present', () => {
  const now = new Date('2026-05-18T08:00:00.000Z');
  const newCard = {
    id: 'w-1',
    ...createInitialCardSchedule(now),
    createdAt: now.toISOString(),
  };

  const baseline = calculateSchedulerReview(newCard, 'good', DEFAULT_SCHEDULER_CONFIG, now);
  assert.equal(baseline.stability, DEFAULT_FSRS_WEIGHTS[2]);

  const customWeights = [...DEFAULT_FSRS_WEIGHTS];
  customWeights[2] = 5; // initial stability for a first "Good"
  const personalized = calculateSchedulerReview(
    newCard,
    'good',
    { ...DEFAULT_SCHEDULER_CONFIG, fsrsWeights: customWeights },
    now,
  );
  assert.equal(personalized.stability, 5);
});
