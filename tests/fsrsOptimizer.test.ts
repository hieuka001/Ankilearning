// ---------------------------------------------------------------------------
// Synthetic learner: review histories generated BY ts-fsrs itself, driven
// by a "true" weight vector that differs clearly from the FSRS-6 defaults
// (fragile initial stability, faster forgetting). A seeded PRNG keeps the
// dataset identical on every run.
// ---------------------------------------------------------------------------

function mulberry32(seed: number) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const TRUE_WEIGHTS = clampFsrsWeights(
  DEFAULT_FSRS_WEIGHTS.map((weight, index) => {
    if (index <= 3) return weight * 0.3;
    if (index === 8) return weight * 1.5;
    if (index === 15) return weight * 0.6;
    if (index === 20) return 0.34;
    return weight;
  }),
)!;

const DAY_MS = 24 * 60 * 60 * 1000;
const SIM_START = Date.parse('2025-01-01T08:00:00.000Z');
const RATING_NAME: Record<Rating, string> = {
  [Rating.Manual]: 'again', // never produced by the simulation
  [Rating.Again]: 'again',
  [Rating.Hard]: 'hard',
  [Rating.Good]: 'good',
  [Rating.Easy]: 'easy',
};

function generateSyntheticCards(cardCount = 160) {
  const engine = fsrs({
    request_retention: DEFAULT_SCHEDULER_CONFIG.desiredRetention,
    maximum_interval: DEFAULT_SCHEDULER_CONFIG.maximumInterval,
    enable_fuzz: false,
    enable_short_term: true,
    learning_steps: DEFAULT_SCHEDULER_CONFIG.learningSteps.map(
      (step) => `${step.amount}${step.unit === 'minute' ? 'm' : 'd'}`,
    ) as never,
    relearning_steps: DEFAULT_SCHEDULER_CONFIG.relearningSteps.map(
      (step) => `${step.amount}${step.unit === 'minute' ? 'm' : 'd'}`,
    ) as never,
    w: [...TRUE_WEIGHTS],
  });
  const rng = mulberry32(42);

  return Array.from({ length: cardCount }, (_, cardIndex) => {
    const start = SIM_START + Math.floor(rng() * 30) * DAY_MS;
    let card = createEmptyCard(new Date(start));
    let at = start;
    const reviewHistory: Array<{ rating: string; reviewTime: string }> = [];
    for (let review = 0; review < 18; review += 1) {
      const late = card.scheduled_days > 0 ? Math.floor(rng() * 4) * DAY_MS : 0;
      at = Math.max(at, card.due.getTime() + late);
      if (at > SIM_START + 700 * DAY_MS) break;
      const retrievability = reviewHistory.length === 0
        ? 1
        : engine.retrievability(card, new Date(at));
      let grade: Rating;
      if (rng() >= retrievability) {
        grade = Rating.Again;
      } else {
        const pick = rng();
        grade = pick < 0.12 ? Rating.Hard : pick < 0.85 ? Rating.Good : Rating.Easy;
      }
      reviewHistory.push({ rating: RATING_NAME[grade], reviewTime: new Date(at).toISOString() });
      card = engine.next(card, new Date(at), grade).card;
    }
    return { id: `synthetic-${cardIndex}`, reviewHistory };
  });
}

